_TEXT_PERSON = re.compile(
    r"(?:נולד|נולדה)\s+ב|(?:היה|הייתה|היתה|הינו|הינה|הוא|היא)\s+(?:רב|רבה|חסיד|שליח|משפיע|רבנית|אשת|בן |בת |נכד|תלמיד|מחבר|"
    r"אדמו\"ר|מנהל|עסקן|איש|נשיא|מלך|תנא|אמורא|מקובל|גאון|דיין|סופר|צייר|זמר|חבר|ראש|רופא|פרופסור|משגיח|מלמד|שוחט|חזן|גבאי)"
)


# כותרות שאינן של אדם גם כשהקטגוריות מטעות ("השלוחים לארץ הקודש" בקטגוריית שלוחים, "ניגון ... (אדמו"ר הזקן)")
_TITLE_NOT_PERSON = re.compile(
    r"^(?:בית|ניגון|ניגוני|ניגונים|ספר|ספרי|קונטרס|מאמר|מאמרי|אגרת|אגרות|קבוצת|השלוחים|רשימת|משפחת|שושלת|חסידות|חסידי|צאצאי|תלמידי|"
    r"מקהלת|ועידת|מבצע|הסתלקות|חתונת|ציור|אוסף|מגילת|סידור|המשך|שו\"ת|פסקי|הלכות|ליקוטי|לקוטי|ילקוט|צוואת|מדליות|התוועדות|"
    r"חלוקת|דבר מלכות|תולדות|שולחן ערוך|תניא|הגדה|תקנות|תפילות|ישיבת|ישיבות|בית חב\"ד|בתי|מוסדות|הצלת|ילדי|מלחמת|בחירות|"
    r"גזירת|קבלת|התייסדות|התפצלות|שיטת|נצחיות|כינוס|ביקורי|נסיעות|סדר יומו|פורטל|קטגוריה|תבנית|משתמש|הבקשות|תפלה|תפילה|"
    r"מנין|קובץ|לשכת|קופת|חברת|דברי ימי|המכתב|הבריחה|הגבלות|השיחה|מהומות|יחידות|תהלוכת|ארמון|נבואות|הדפסת|חדר|חזרת|לימוד)(?:\s|$)"
)
# בלי קטגוריות – גם כותרות של מושגים/ימים
_TITLE_WEAK = re.compile(r"^(?:יום|ליל|ערב|שבת|חג|צום|תענית|ימי|בית|כפר|שכונת|ועד|כנס|ארגון|מוסד|ביקור|מסע|ראש חודש|עמוד|מענה|תורת|"
                         r"שער|שערי|אנשי|רבני|שלוחי|עולי|נשות|ברכת|התפילה|מפתח|פגישה|שנת|פרשת|הלכה)(?:\s|$)")


def is_person_page(page: dict) -> bool:
    title = page.get("title") or ""
    if _TITLE_NOT_PERSON.match(title) or title.endswith("(פירושונים)") or title.endswith("(שם)"):
        return False
    cats = page.get("categories") or []
    if any(POSITIVE.search(c) and not NEGATIVE.search(c) for c in cats):
        return True
    if cats:
        return False
    if _TITLE_WEAK.match(title):
        return False
    text = page.get("wikitext") or ""
    return "{{אינפו" in text or "{{דמות" in text or bool(_TEXT_PERSON.search(text[:1500]))
