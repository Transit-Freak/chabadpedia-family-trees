    r"דיינ|שוחט|סופרי|מלמד|משגיח|חברי|כותבי|זמר|אמני|עיתונאי|חוקרי|עורכי|מנהלי|מייסדי|בוגרי|נציגי|רופאי|ניצולי|נרצח|קדושי|"
    r"הרוגי|ילידי|נפטרי|ממלאי|מזכיר|מחנכ|מרצי|אנשי|משפחת |צאצאי|בני |חתני|יהודי|גבאי|מגידי|חזני|שדר|פעילי|תמימים|בעלי|"
    r"מנגנים|מלחינ|משוררי|ציירי|צלמי|מו\"לים|נגידי|תורמי|פרופסור|קציני|חיילי|שבויי|אסירי|עולי|מתנגדי|נשיאי|ראשונים|אחרונים|"
    r"תנאים|אמוראים|גאונים|גדולי|פוסקים|חכמי|נביאים|מלכי|שופטי|פוליטיקאי|מדינאי|ידידי|דמויות|צדיקים|מגורשי|נושאי|מדפיסי|"
    r"גויים|מומרים|רשעים|אבות|אמהות|שבטי|צוות |מנהיגי|סגני|שרים|שרי |ראש ה|בעל ה|הבעל|ר\"מים|רמ\"ים|שו\"בים|מוהלים|סופר|"
    r"ילדי|אחיינ|נכדי|חתנ|נינ|גרים|גיורות|מקורבי|משמשי|מלווי|נהגי|שומרי|גרי|מינים"
