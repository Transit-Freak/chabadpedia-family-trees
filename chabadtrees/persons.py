    r"^התוועדויות|^כינוס|^מבנ|^מוזיאונ|^מלחמ|^רשימ|^שירים|^חוברות|^דיסקים|^אלבומ|^ספריות|^הוצאות|^עלונים|^יומנ|^מכתב|^מענ|"
    r"^תקנ|^סגול|^הגדר|^ביטוי|^מילים|^שמות|^כלי|^בגד|^מאכל|^מטבע|^חפצ|^אביזר|^מכשיר|^חלוקות|^במחיצת|^המשכים|^רמב\"ם|^תניא|"
    r"^חומש|^שלימות|^הקהל|^תורת|^שליחות$|^מחלקות|^קהילות|^מדליות|^אוספ|^עמוד|^מסע|^הצלת|^גזיר|^התפצל|^התייסד|^הסתלק|^קבלת|"
